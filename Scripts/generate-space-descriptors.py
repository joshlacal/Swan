#!/usr/bin/env python3
"""Regenerate the compact Spaces route registry from the pinned lexicon corpus."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--reference-root", type=Path, required=True)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
profile_id = "permissioned-data-0016-2026-10-22"
schemas = sorted([*args.reference_root.glob("lexicons/com/atproto/space/*.json"),
                  *args.reference_root.glob("lexicons/com/atproto/simplespace/*.json")])
if len(schemas) != 30:
    raise SystemExit("expected the exact 30-file October 22 corpus")
profile = json.loads((root / "Profiles" / f"{profile_id}.json").read_text())
ordered = {json.loads(path.read_text())["id"]: json.loads(path.read_text()) for path in schemas}
quote = lambda value: "nil" if value is None else json.dumps(value)
rows = []
for nsid in profile["endpoints"]:
    main = ordered[nsid]["defs"]["main"]
    errors = ", ".join(quote(error["name"]) for error in main.get("errors", []))
    rows.append(f'        .init(nsid: {quote(nsid)}, kind: .{main["type"]}, '
                f'inputEncoding: {quote(main.get("input", {}).get("encoding"))}, '
                f'outputEncoding: {quote(main.get("output", {}).get("encoding"))}, declaredErrors: [{errors}]),')
source = '''// Generated by Scripts/generate-space-descriptors.py; do not edit.
import Foundation
import SwanCore

public struct SpaceDeclarationDescriptor: Sendable, Codable, Equatable {
    public let nsid: String
    public let keyType: String
    public let name: String
    public let collections: [String]
}

public enum XRPCMethodKind: String, Sendable, Codable {
    case query
    case procedure
    case subscription
}

public struct XRPCMethodDescriptor: Sendable, Codable, Equatable {
    public let nsid: String
    public let kind: XRPCMethodKind
    public let inputEncoding: String?
    public let outputEncoding: String?
    public let declaredErrors: [String]
}

public enum PermissionedData0016 {
    public static let profileID = "%s"
    public static let methods: [XRPCMethodDescriptor] = [
%s
    ]
}

public protocol XRPCServerRequestContext: Sendable {}

public protocol XRPCServerHandler: Sendable {
    associatedtype Context: XRPCServerRequestContext
    associatedtype Input: Sendable
    associatedtype Output: Sendable
    func handle(_ input: Input, context: Context) async throws -> Output
}
''' % (profile_id, "\n".join(rows))
outputs = {
    root / "Sources/SwanSpacesWire/SwanSpacesWire.swift": source.encode(),
    root / "Profiles" / f"{profile_id}.lexicons.sha256": "".join(
        f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.relative_to(args.reference_root / 'lexicons')}\n"
        for path in schemas).encode(),
}
outputs[root / "Profiles" / f"{profile_id}.generated-wire.sha256"] = (
    hashlib.sha256(source.encode()).hexdigest() + "  Sources/SwanSpacesWire/SwanSpacesWire.swift\n").encode()
for path, data in outputs.items():
    if args.check:
        if path.read_bytes() != data:
            raise SystemExit(f"generated artifact differs: {path.relative_to(root)}")
    else:
        path.write_bytes(data)
print(f"{'Verified' if args.check else 'Generated'} {len(rows)} methods from {len(schemas)} lexicons")
