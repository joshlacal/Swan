#!/usr/bin/env bash
# Regenerates Sources/SwanHTTP/SwanBrowserStyleSheet.swift from the markup in
# SwanBrowserPages.swift and ScopeDescription.swift using Tailwind CSS v4 +
# daisyUI 5.
#
# Run after changing any class name in either file: the build is tree-shaken,
# so an unbuilt class has no styles. Requires npx.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
pages="$root/Sources/SwanHTTP/SwanBrowserPages.swift"
scopes="$root/Sources/SwanHTTP/ScopeDescription.swift"
output="$root/Sources/SwanHTTP/SwanBrowserStyleSheet.swift"

tooling="$root/Scripts/browser-css-tooling"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cp "$pages" "$work/pages.swift"
cp "$scopes" "$work/scopes.swift"
cat > "$work/input.css" <<CSS
@import "tailwindcss" source(none);
@source "./pages.swift";
@source "./scopes.swift";
@plugin "daisyui" { themes: light --default, dark --prefersdark; }
CSS
cp "$tooling/package.json" "$work/package.json"
cp "$tooling/package-lock.json" "$work/package-lock.json"
(cd "$work" && npm ci --ignore-scripts --no-audit --no-fund --silent)
(cd "$work" && npx --no-install @tailwindcss/cli -i input.css -o out.css --minify)

{
  cat <<'HEADER'
// Generated by Scripts/build-browser-css.sh. Do not edit by hand.
//
// Tailwind CSS v4 + daisyUI 5, tree-shaken against the markup in
// SwanBrowserPages.swift and ScopeDescription.swift. Both are MIT licensed;
// see THIRD_PARTY_NOTICES.md.

extension SwanBrowserPages {
    static let styleSheet = #"""
HEADER
  # The literal must be byte-exact: the served CSP hash is derived from it.
  printf '%s\n' "$(cat "$work/out.css")"
  cat <<'FOOTER'
"""#
}
FOOTER
} > "$output"

echo "wrote $output ($(wc -c < "$output") bytes)"
