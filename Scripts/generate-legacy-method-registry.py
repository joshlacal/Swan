#!/usr/bin/env python3
"""Generate the finite legacy service-auth method registry from pinned lexicons."""
import argparse, hashlib, json, pathlib, sys, tempfile, os

parser = argparse.ArgumentParser(add_help=False)
parser.add_argument('--root', type=pathlib.Path)
parser.add_argument('--output', type=pathlib.Path)
parser.add_argument('--source-revision', type=str)
args = parser.parse_args([a for a in sys.argv[1:] if a != '--check'])
ROOT = args.root or pathlib.Path(os.environ.get('SWAN_PINNED_LEXICONS', pathlib.Path(__file__).parents[2] / 'Petrel/atproto/lexicons'))
OUT = args.output or pathlib.Path(__file__).parents[1] / 'Sources/SwanStorage/GeneratedLegacyMethodRegistry.swift'
source_revision = args.source_revision
if not source_revision:
    import subprocess
    try:
        proc = subprocess.run(['git', '-C', str(ROOT / '..'), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True)
        source_revision = proc.stdout.strip()
    except Exception:
        try:
            proc = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True)
            source_revision = proc.stdout.strip()
        except Exception:
            source_revision = 'unknown'
allowed = ('app.bsky.', 'chat.bsky.', 'tools.ozone.')
exact = {
    'com.atproto.moderation.createReport': 'rpc:com.atproto.moderation',
    'com.atproto.label.queryLabels': 'rpc:com.atproto.label',
    'com.atproto.repo.getRecord': 'repo:read',
    'com.atproto.repo.createRecord': 'repo:write',
    'com.atproto.repo.deleteRecord': 'repo:write',
    'com.atproto.repo.listRecords': 'repo:read',
    'com.atproto.repo.describeRepo': 'repo:read',
    'com.atproto.sync.getBlob': 'blob:read',
    'com.atproto.identity.resolveHandle': 'identity:read',
}
local = {
    'com.atproto.server.createSession': set(), 'com.atproto.server.refreshSession': set(), 'com.atproto.server.getSession': set(), 'com.atproto.server.deleteSession': set(),
    'com.atproto.server.getServiceAuth': set(), 'com.atproto.server.createAppPassword': set(), 'com.atproto.server.listAppPasswords': set(), 'com.atproto.server.revokeAppPassword': set(),
    'com.atproto.repo.applyWrites': {'repo:write'}, 'com.atproto.repo.createRecord': {'repo:write'}, 'com.atproto.repo.deleteRecord': {'repo:write'}, 'com.atproto.repo.describeRepo': {'repo:read'},
    'com.atproto.repo.getRecord': {'repo:read'}, 'com.atproto.repo.listRecords': {'repo:read'}, 'com.atproto.repo.putRecord': {'repo:write'}, 'com.atproto.repo.uploadBlob': {'blob:write'},
    'com.atproto.sync.getBlob': {'blob:read'}, 'com.atproto.sync.getLatestCommit': {'repo:read'}, 'com.atproto.sync.getRepo': {'repo:read'}, 'com.atproto.sync.getRepoStatus': {'repo:read'},
    'com.atproto.identity.resolveHandle': {'identity:read'}, 'app.bsky.actor.getPreferences': {'rpc:app.bsky'}, 'app.bsky.actor.putPreferences': {'rpc:app.bsky'},
}
supplemental = {'app.bsky.actor.getPreferencesExtended': 'rpc:app.bsky'}
denied = set()
rows = []
dig = hashlib.sha256()
for path in sorted(ROOT.rglob('*.json')):
    raw = path.read_bytes(); dig.update(path.relative_to(ROOT).as_posix().encode()); dig.update(raw)
    obj = json.loads(raw); nsid = obj.get('id', '')
    if nsid in denied or not (nsid.startswith(allowed) or nsid in exact): continue
    main = obj.get('defs', {}).get('main', {})
    if main.get('type') not in {'query', 'procedure', 'subscription'}: continue
    scope = exact.get(nsid)
    if scope is None:
        scope = 'rpc:' + next(p for p in allowed if nsid.startswith(p)).rstrip('.')
    rows.append((nsid, scope, 'proxyExplicit' if nsid in exact else 'proxyDefault'))
by_method = {method: (method, scope, disposition) for method, scope, disposition in rows}
for nsid, scopes in local.items(): by_method[nsid] = (nsid, ' '.join(sorted(scopes)), 'local')
for nsid, scope in supplemental.items(): by_method[nsid] = (nsid, scope, 'proxyDefault')
rows = sorted(by_method.values())
target = OUT
if '--check' in sys.argv:
    target = pathlib.Path(tempfile.mkstemp(prefix='legacy-registry-', suffix='.swift')[1])
with target.open('w') as f:
    f.write('// Generated by Scripts/generate-legacy-method-registry.py; do not edit.\n')
    f.write(f'// Source: Petrel/atproto/lexicons; revision: {source_revision}; digest: {dig.hexdigest()}\n')
    f.write('import Foundation\n\npublic enum GeneratedLegacyMethodRegistry {\n')
    f.write('    public enum RoutingDisposition: String, Sendable { case local, proxyExplicit, proxyDefault }\n')
    f.write(f'    public static let sourceDigest = "{dig.hexdigest()}"\n')
    f.write(f'    public static let sourceRevision = "{source_revision}"\n')
    f.write('    public static let declarations: [String: Set<String>] = [\n')
    for i, (method, scope, _) in enumerate(rows):
        value = '[]' if not scope else '["' + scope + '"]'
        f.write('        "' + method + '": ' + value + (',' if i + 1 < len(rows) else '') + '\n')
    f.write('    ]\n    public static let routing: [String: RoutingDisposition] = [\n')
    for i, (method, _, disposition) in enumerate(rows):
        f.write('        "' + method + '": .' + disposition + (',' if i + 1 < len(rows) else '') + '\n')
    f.write('    ]\n}\n')
print(f'generated {len(rows)} methods; digest {dig.hexdigest()}')
if '--check' in sys.argv:
    expected = OUT.read_bytes()
    actual = target.read_bytes()
    target.unlink()
    if expected != actual:
        raise SystemExit('generated registry is stale; rerun generator')
