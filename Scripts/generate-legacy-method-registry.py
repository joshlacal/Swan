#!/usr/bin/env python3
"""Generate the finite legacy service-auth method registry from pinned lexicons."""
import hashlib, json, pathlib, sys, tempfile

ROOT = pathlib.Path('/Users/joshlacalamito/Developer/Catbird+Petrel/Petrel/atproto/lexicons')
OUT = pathlib.Path(__file__).parents[1] / 'Sources/SwanStorage/GeneratedLegacyMethodRegistry.swift'
allowed = ('app.bsky.', 'chat.bsky.', 'tools.ozone.')
exact = {
    'com.atproto.moderation.createReport': 'rpc:com.atproto.moderation',
    'com.atproto.label.queryLabels': 'rpc:com.atproto.label',
    'com.atproto.repo.getRecord': 'repo:read',
    'com.atproto.repo.createRecord': 'repo:write',
    'com.atproto.repo.deleteRecord': 'repo:write',
    'com.atproto.repo.listRecords': 'repo:read',
    'com.atproto.repo.describeRepo': 'repo:read',
    'com.atproto.sync.getBlob': 'blob:read',
    'com.atproto.identity.resolveHandle': 'identity:read',
}
denied = {'com.atproto.server.createSession', 'com.atproto.server.refreshSession'}
rows = []
dig = hashlib.sha256()
for path in sorted(ROOT.rglob('*.json')):
    raw = path.read_bytes(); dig.update(path.relative_to(ROOT).as_posix().encode()); dig.update(raw)
    obj = json.loads(raw); nsid = obj.get('id', '')
    if nsid in denied or not (nsid.startswith(allowed) or nsid in exact): continue
    main = obj.get('defs', {}).get('main', {})
    if main.get('type') not in {'query', 'procedure', 'subscription'}: continue
    scope = exact.get(nsid)
    if scope is None:
        scope = 'rpc:' + next(p for p in allowed if nsid.startswith(p)).rstrip('.')
    rows.append((nsid, scope))
rows = sorted(set(rows))
target = OUT
if '--check' in sys.argv:
    target = pathlib.Path(tempfile.mkstemp(prefix='legacy-registry-', suffix='.swift')[1])
with target.open('w') as f:
    f.write('// Generated by Scripts/generate-legacy-method-registry.py; do not edit.\n')
    f.write('// Source: Petrel/atproto/lexicons; digest: ' + dig.hexdigest() + '\n')
    f.write('import Foundation\n\npublic enum GeneratedLegacyMethodRegistry {\n')
    f.write('    public static let sourceDigest = "' + dig.hexdigest() + '"\n')
    f.write('    public static let declarations: [String: Set<String>] = [\n')
    for i, (method, scope) in enumerate(rows):
        f.write('        "' + method + '": ["' + scope + '"]' + (',' if i + 1 < len(rows) else '') + '\n')
    f.write('    ]\n}\n')
print(f'generated {len(rows)} methods; digest {dig.hexdigest()}')
if '--check' in sys.argv:
    expected = OUT.read_bytes()
    actual = target.read_bytes()
    target.unlink()
    if expected != actual:
        raise SystemExit('generated registry is stale; rerun generator')
